import { readFile, readdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const assets = (
  await readdir(new URL("../dist/assets/", import.meta.url))
).filter((file) => /\.(js|css)$/.test(file));
const urls = [
  "./",
  "./index.html",
  "./favicon.svg",
  "./tray-demo/portal.ptnk.png",
  "./tray-demo/calibration.json",
  ...(await readdir(new URL("../dist/ptnk-normalized/", import.meta.url))).filter(file => file.endsWith(".jpg")).map(file => "./ptnk-normalized/"+file),
  ...assets.map((file) => "./assets/" + file),
];
const hash = createHash("sha256");
for (const url of urls.filter((url) => url !== "./"))
  hash.update(
    await readFile(new URL("../dist/" + url.slice(2), import.meta.url)),
  );
hash.update(await readFile(new URL(import.meta.url)));
const version = "ecotray-stage-" + hash.digest("hex").slice(0, 16);
const source = `// Generated by scripts/build-offline.mjs. API responses are never cached.
const CACHE=${JSON.stringify(version)};
const URLS=${JSON.stringify(urls)};
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(URLS)).then(()=>self.skipWaiting())));
self.addEventListener('activate',event=>event.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(key=>key.startsWith('ecotray-stage-')&&key!==CACHE).map(key=>caches.delete(key)))).then(()=>self.clients.claim())));
self.addEventListener('fetch',event=>{
 const url=new URL(event.request.url);
 if(event.request.method!=='GET'||url.origin!==self.location.origin||url.pathname.includes('/api/'))return;
 event.respondWith(caches.open(CACHE).then(async cache=>{
  const cached=await cache.match(event.request);if(cached)return cached;
  try{return await fetch(event.request);}catch(error){if(event.request.mode==='navigate'){const index=await cache.match('./index.html');if(index)return index;}if(event.request.destination==='image')return new Response('<svg xmlns="http://www.w3.org/2000/svg" width="400" height="240" viewBox="0 0 400 240"><rect width="400" height="240" fill="#eef3ee"/><text x="200" y="120" text-anchor="middle" fill="#45634f" font-size="18">Ảnh gốc cần kết nối mạng</text></svg>',{headers:{'Content-Type':'image/svg+xml; charset=utf-8'}});throw error;}
 }));
});
self.addEventListener('message',event=>{if(event.data==='OFFLINE_READY')event.ports[0]?.postMessage({ready:true,cache:CACHE});});
`;
await writeFile(new URL("../dist/sw.js", import.meta.url), source);
console.log(
  "Offline stage cache generated: " +
    version +
    " (" +
    urls.length +
    " assets).",
);
